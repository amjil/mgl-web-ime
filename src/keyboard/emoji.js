/**
 * @param {string} [id]
 */
export function getEmojiCategory(id = "smileys") {
  return EMOJI_CATEGORIES.find((c) => c.id === id) ?? EMOJI_CATEGORIES[0];
}

/**
 * @param {string[]} items
 * @param {number} page
 * @param {number} [pageSize]
 */
export function pageEmoji(items, page = 0, pageSize = MOBILE_EMOJI_PAGE_SIZE) {
  const list = items ?? [];
  const size = Math.max(1, pageSize);
  const pages = Math.max(1, Math.ceil(list.length / size) || 1);
  const p = Math.max(0, Math.min(page, pages - 1));
  return {
    items: list.slice(p * size, p * size + size),
    page: p,
    pages,
    pageSize: size,
  };
}

/**
 * @param {string} [categoryId]
 * @param {number} [page]
 * @param {number} [pageSize]
 */
export function getEmojiPage(categoryId, page = 0, pageSize = MOBILE_EMOJI_PAGE_SIZE) {
  const category = getEmojiCategory(categoryId);
  return { category, ...pageEmoji(category.items, page, pageSize) };
}
